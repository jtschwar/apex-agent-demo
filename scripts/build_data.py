"""Write assets/data.js from the CSVs in materials/, so index.html works from file://."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def rows(name, numeric):
    out = []
    for r in csv.DictReader(open(ROOT / "materials" / name)):
        for k in numeric:
            r[k] = float(r[k]) if r[k] not in ("", None) else None
        out.append(r)
    return out


ctf = rows("ctf_results.csv", ["defocus_u_A", "defocus_v_A", "astigmatism_A",
                               "ctf_max_resolution_A", "ctf_figure_of_merit"])
classes = rows("class2d_classes.csv", ["class", "particle_fraction", "particles",
                                       "estimated_resolution_A"])
skill = (ROOT / "skill" / "cryoem-review" / "SKILL.md").read_text()
(ROOT / "assets" / "data.js").write_text(
    "// generated by scripts/build_data.py; do not edit\n"
    "window.CTF = %s;\nwindow.CLASSES = %s;\nwindow.SKILL_MD = %s;\n"
    % (json.dumps(ctf), json.dumps(classes), json.dumps(skill)))
print("wrote assets/data.js:", len(ctf), "micrographs,", len(classes), "classes")
